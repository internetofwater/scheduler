#!/usr/bin/env bash
# Pull the SPARQL queries used by the upstream explorer UI
# (https://github.com/internetofwater/explorer.geoconnex.us) from GHCR, where its
# main branch publishes them as an OCI artifact tagged with each commit sha. Each
# query is written to its own file in userCode/assetGroups/queries/explorer/,
# which is regenerated from scratch on every pull, so don't edit it by hand; put
# custom checks directly in userCode/assetGroups/queries/ instead. The queries are
# run against the qlever index by the `geoconnex_sparql_query_check` asset check,
# so bump them manually with `make pullQueries` whenever the explorer changes them.
#
# Usage: scripts/pull_explorer_queries.sh [tag-or-digest]
#   default: the pinned explorer main commit below; pass `latest` for the newest main
# Uses a local `oras` if installed, otherwise runs oras through docker.
set -euo pipefail

# explorer.geoconnex.us main commit the queries are pinned to
PINNED_COMMIT="2bef5ed65c102ea793807f4e384f472f0e437f22"

REF="${1:-$PINNED_COMMIT}"
REPOSITORY="ghcr.io/internetofwater/explorer-sparql-statements"
ORAS_IMAGE="ghcr.io/oras-project/oras:v1.2.0"
# the upstream workflow publishes every query in this one json file, keyed by query name
ARTIFACT_FILE="sparql-queries.json"
DEST="$(cd "$(dirname "$0")/.." && pwd)/userCode/assetGroups/queries/explorer"

case "$REF" in
  sha256:*) TARGET="$REPOSITORY@$REF" ;;
  *) TARGET="$REPOSITORY:$REF" ;;
esac

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "Pulling $TARGET"
if command -v oras >/dev/null 2>&1; then
  (cd "$TMP" && oras pull "$TARGET" | tee pull.log)
else
  docker run --rm --user "$(id -u):$(id -g)" -v "$TMP:/out" -w /out "$ORAS_IMAGE" pull "$TARGET" | tee "$TMP/pull.log"
fi
DIGEST="$(grep -o 'sha256:[0-9a-f]*$' "$TMP/pull.log" | tail -1 || true)"

test -s "$TMP/$ARTIFACT_FILE" || { echo "artifact did not contain $ARTIFACT_FILE" >&2; exit 1; }

# write each query to explorer/<name>.sparql, replacing whatever was pulled before
rm -rf "$DEST"
mkdir -p "$DEST"
python3 -I - "$TMP/$ARTIFACT_FILE" "$DEST" <<'EOF'
import json
import re
import sys
from pathlib import Path

queries = json.loads(Path(sys.argv[1]).read_text())
assert queries, "artifact contained no queries"
for name, text in queries.items():
    assert isinstance(text, str), f"query {name} is not a string"
    assert re.fullmatch(r"[A-Za-z0-9_-]+", name), f"unexpected query name {name!r}"
    Path(sys.argv[2], f"{name}.sparql").write_text(text.strip() + "\n")
print("queries:", ", ".join(queries))
EOF

# record exactly which artifact the queries came from
cat > "$DEST/SOURCE" <<EOF
# Generated by scripts/pull_explorer_queries.sh; do not edit this directory by hand.
artifact: $TARGET
digest: $DIGEST
EOF
echo "Wrote $DEST (digest: $DIGEST)"
